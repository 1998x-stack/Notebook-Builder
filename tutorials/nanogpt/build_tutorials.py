def spec_fingerprint(spec: dict) -> str:
    """Canonical, output-independent hash of the tutorial authoring contract."""
    return hashlib.sha256(json.dumps(spec, sort_keys=True, ensure_ascii=False,
                           separators=(',', ':')).encode('utf-8')).hexdigest()


def verify_spec_matches_notebook(notebook: Path, spec: dict) -> str:
    """Reject stale .ipynb code without overwriting user-edited notebooks.

    Executed outputs/Cell IDs are deliberately excluded; a tutorial's teaching
    source, order and type must be identical to its source specification.
    """
    import nbformat
    actual = nbformat.read(notebook, as_version=4)
    expected = ([('markdown', f"# {spec['title']}")] if spec.get('title') else [])
    expected.extend((c.get('cell_type', 'code'), c.get('source', '')) for c in spec['cells'])
    observed = [(c.cell_type, c.source) for c in actual.cells]
    if observed != expected:
        raise nbcore.ConflictError(
            f"Tutorial spec drift for {notebook.name}: source differs from latest spec. "
            "Use --force to rebuild intentionally; existing file is untouched.")
    metadata_hash = actual.metadata.get(nbcore.META_KEY, {}).get('spec_sha256')
    current_hash = spec_fingerprint(spec)
    if metadata_hash is not None and metadata_hash != current_hash:
        raise nbcore.ConflictError(
            f"Tutorial spec hash mismatch for {notebook.name}; use --force to rebuild")
    return current_hash


def run_series(*, list_only=False, build=False, execute=False, html=False, force=False, only=None, timeout=120):
    selected=[c for c in chapters() if not only or any(c['slug'].startswith(s) for s in only)]
    if not selected:
        raise ValueError('No tutorial matches --only')
    if list_only or not (build or execute or html):
        return {'series':'nanoGPT', 'source_commit':UPSTREAM_SHA,'count':len(selected),
                'chapters':[{'slug':c['slug'],'title':c['title'],'topic':c['topic'],'goals':c['goals']} for c in selected]}
    (HERE/'notebooks').mkdir(parents=True,exist_ok=True)
    (HERE/'specs').mkdir(parents=True,exist_ok=True)
    (HERE/'outputs'/'figures').mkdir(parents=True,exist_ok=True)
    items=[]
    for chapter in selected:
        slug=chapter['slug']
        notebook=HERE/'notebooks'/f'{slug}.ipynb'
        spec_file=HERE/'specs'/f'{slug}.json'
        spec={'title':chapter['title'],'cells':[M(PREFACE)]+chapter['cells']}
        spec_file.write_text(json.dumps(spec,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
        current={'slug':slug,'notebook':str(notebook),'notebook_relative':str(notebook.relative_to(HERE)),
                 'status':'unchanged', 'spec_sha256':spec_fingerprint(spec)}
        if notebook.exists():
            if force and (build or execute):
                nbcore.from_spec(notebook,spec_file,overwrite=True)
                current['status']='rebuilt'
            else:
                verify_spec_matches_notebook(notebook,spec)
                current['status']='verified-existing'
        elif build or execute:
            nbcore.from_spec(notebook,spec_file)
            current['status']='built'
        else:
            raise FileNotFoundError(f'{notebook} does not exist; use --build')
        current['cell_count']=len(nbcore.describe(notebook)['cells'])
        if execute:
            start=time.monotonic()
            nbcore.execute(notebook,timeout=timeout,cwd=HERE/'notebooks')
            current['execution_seconds']=round(time.monotonic()-start,2)
            current['status']+=' + executed'
        import nbformat
        doc=nbformat.read(notebook,as_version=4)
        code_cells=[c for c in doc.cells if c.cell_type=='code']
        current['code_cells']=len(code_cells)
        current['print_cells']=sum(any(o.output_type=='stream' and 'stdout'==o.name for o in c.outputs) for c in code_cells)
        current['figure_cells']=sum(any(o.output_type in ('display_data','execute_result') and ('image/png' in o.get('data',{})) for o in c.outputs) for c in code_cells)
        current['errors']=sum(any(o.output_type=='error' for o in c.outputs) for c in code_cells)
        if execute:
            quality=quality_inspect(notebook,require_executed=True,min_print_cells=2,min_figure_cells=1)
            current['quality']={'passed':quality['passed'], 'metrics':quality['metrics'],
                                'violations':quality['violations']}
            if not quality['passed']:
                raise AssertionError(f'{slug}: quality checks failed: {quality["violations"]}')
        if html:
            output=HERE/'outputs'/f'{slug}.html'
            nbcore.export_html(notebook,output)
            current['html']=str(output)
            current['html_relative']=str(output.relative_to(HERE))
        current['sha256']=hashlib.sha256(notebook.read_bytes()).hexdigest()
        items.append(current)
    result={'series':'nanoGPT','source_commit':UPSTREAM_SHA, 'builder':str(BUILDER),
            'helper_sha256':hashlib.sha256(Path(__file__).with_name('nanogpt_edu.py').read_bytes()).hexdigest(),
            'tutorials':items,'count':len(items)}
    (HERE/'outputs'/'manifest.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    if html and len(selected)==len(chapters()):
        import runpy
        result['index']=runpy.run_path(str(HERE/'make_index.py'))['build_index']()
    return result


def main(argv=None):
    parser=argparse.ArgumentParser(description='Notebook Builder tutorial series for karpathy/nanoGPT')
    parser.add_argument('--list',action='store_true');parser.add_argument('--build',action='store_true')
    parser.add_argument('--execute',action='store_true');parser.add_argument('--html',action='store_true')
    parser.add_argument('--force',action='store_true');parser.add_argument('--only',nargs='*')
    parser.add_argument('--timeout',type=int,default=120)
    args=parser.parse_args(argv)
    result=run_series(list_only=args.list,build=args.build,execute=args.execute,html=args.html,
                      force=args.force,only=args.only,timeout=args.timeout)
    print(json.dumps(result,ensure_ascii=False,indent=2))
    return 0

